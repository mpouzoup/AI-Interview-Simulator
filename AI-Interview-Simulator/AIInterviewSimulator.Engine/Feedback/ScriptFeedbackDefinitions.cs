    internal static (string Id, string Text) Select(IReadOnlyList<CriterionEvidence> criteria)
    {
        if (criteria.Any(c => c.Reason == EvidenceReason.ConflictingEvidence))
            return ("q3.fallback", Fallback);
        if (criteria[0].Reason == EvidenceReason.ExplicitNonAnswer)
            return ("q3.example", "Μπορείτε να επιλέξετε ένα μικρό περιστατικό από σπουδές, εργασία ή προσωπικό έργο. Περιγράψτε τη δυσκολία, τι κάνατε εσείς και πώς εξελίχθηκε η κατάσταση.");
        var p = criteria[0].State == CriterionState.Detected;
        var a = criteria[1].State == CriterionState.Detected;
        var r = criteria[2].State == CriterionState.Detected;
        if (p && a && r)
            return ("q3.complete", "Στην απάντησή σας αναγνωρίζονται στοιχεία για τη δυσκολία, τις προσωπικές σας ενέργειες και την έκβαση. Μπορείτε να κάνετε ακόμη πιο σαφή τη σύνδεση ανάμεσα στις ενέργειές σας και στην εξέλιξη της κατάστασης.");
        if (p && a)
            return ("q3.result", "Η απάντησή σας περιγράφει τη δυσκολία και προσωπικές σας ενέργειες. Για να γίνει ακόμη πιο σαφής, μπορείτε να εξηγήσετε και ποια ήταν η τελική έκβαση, ακόμη και αν δεν ήταν η επιθυμητή.");
        if (p && !a)
            return ("q3.action", "Η απάντησή σας δίνει στοιχεία για τη δυσκολία που αντιμετωπίσατε. Μπορείτε να διευκρινίσετε ποια συγκεκριμένα βήματα κάνατε εσείς για να την αντιμετωπίσετε.");
        if (a && r)
            return ("q3.problem", "Η απάντησή σας δίνει στοιχεία για προσωπικές ενέργειες και έκβαση. Μπορείτε να κάνετε πιο συγκεκριμένο το αρχικό πρόβλημα και το πλαίσιο στο οποίο προέκυψε.");
        return ("q3.fallback", Fallback);
    }

