    internal static (string Id, string Text) Select(int stageNumber, Stage stage, IReadOnlyList<CriterionEvidence> criteria)
    {
        var prefix = $"q{stageNumber}.";
        if (criteria.Any(c => c.Reason == EvidenceReason.ConflictingEvidence) ||
            !criteria.Any(c => c.State == CriterionState.Detected))
            return (prefix + "fallback", stage.Fallback);
        for (var i = 0; i < stage.Criteria.Length; i++)
            if (stage.Criteria[i].Required && criteria[i].State != CriterionState.Detected)
                return (prefix + stage.Criteria[i].Id, stage.Criteria[i].Prompt);
        if (stage.Criteria.Where((c, i) => !c.Required && criteria[i].State != CriterionState.Detected).Any())
            return (prefix + "enrich", stage.Enrichment);
        return (prefix + "complete", stage.Complete);
    }
