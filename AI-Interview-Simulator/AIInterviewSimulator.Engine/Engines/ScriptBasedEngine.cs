using AIInterviewSimulator.Data.Entities;
using AIInterviewSimulator.Engine.Interfaces;

namespace AIInterviewSimulator.Engine.Engines;

public class ScriptBasedEngine : IInterviewEngine
{
    private readonly List<string> _questions;

    public ScriptBasedEngine()
    {
        _questions = new List<string>
        {
            "Καλώς ορίσατε στη συνέντευξη. Θα θέλατε να μας κάνετε μια σύντομη αυτοπαρουσίαση, αναφέροντας στοιχεία από το υπόβαθρο, τις εμπειρίες ή τις δεξιότητές σας που θεωρείτε σχετικά με τη θέση;",

            "Τι σας ενδιαφέρει στη συγκεκριμένη θέση και ποιοι είναι οι βασικοί λόγοι για τους οποίους θα θέλατε να εργαστείτε σε αυτήν;",

            "Περιγράψτε μια περίπτωση από εργασία, σπουδές ή κάποιο έργο όπου χρειάστηκε να αντιμετωπίσετε ένα πρόβλημα. Πώς προσεγγίσατε την κατάσταση και ποιο ήταν το αποτέλεσμα;",

            "Περιγράψτε μια εμπειρία από εργασία, σπουδές ή κάποιο έργο όπου χρειάστηκε να συνεργαστείτε με άλλα άτομα για την επίτευξη ενός κοινού στόχου. Ποιος ήταν ο δικός σας ρόλος;",

            "Περιγράψτε μια περίπτωση από εργασία, σπουδές ή κάποιο έργο όπου βρεθήκατε υπό πίεση ή αντιμετωπίσατε μια ιδιαίτερα απαιτητική κατάσταση. Πώς τη διαχειριστήκατε;",

            "Περιγράψτε μια περίπτωση από εργασία, σπουδές ή κάποιο έργο όπου κάτι δεν εξελίχθηκε όπως περιμένατε. Πώς προσαρμοστήκατε και τι μάθατε από την εμπειρία;",

            "Ποιοι είναι οι βασικοί επαγγελματικοί σας στόχοι για τα επόμενα χρόνια και με ποιον τρόπο θεωρείτε ότι η συγκεκριμένη θέση θα μπορούσε να συμβάλει στην επίτευξή τους;"
        };
    }

    public Task<string> GetNextQuestionAsync(
        int stageNumber,
        List<UserAnswer> previousAnswers)
    {
        int index = stageNumber - 1;

        if (index >= 0 && index < _questions.Count)
        {
            return Task.FromResult(_questions[index]);
        }

        return Task.FromResult(
            "Η συνέντευξη έχει ολοκληρωθεί. Σας ευχαριστούμε πολύ!");
    }
}
